# --- [ 1. OPEN A TERMINAL WHEN LAUNCHED FROM A FILE MANAGER ] ----------------
respawn_in_terminal() {
    local self t
    self=$(readlink -f "$0")
    export ULSET_TERMINAL_SPAWNED=1
    for t in konsole gnome-terminal kgx xfce4-terminal mate-terminal lxterminal qterminal \
             deepin-terminal tilix alacritty kitty xterm x-terminal-emulator; do
        command -v "$t" >/dev/null 2>&1 || continue
        case $t in
            gnome-terminal)             exec "$t" -- "$self" ;;
            xfce4-terminal|mate-terminal) exec "$t" -x "$self" ;;
            kitty)                      exec "$t" "$self" ;;
            *)                          exec "$t" -e "$self" ;;
        esac
    done
    return 1
}
if [[ -z $ACTION && ! -t 0 && -z ${ULSET_TERMINAL_SPAWNED:-} ]]; then
    respawn_in_terminal || true
fi

