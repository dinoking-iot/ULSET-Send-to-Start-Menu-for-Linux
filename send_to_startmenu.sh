ERR_LIST=()
STEP=0
STEP_TOTAL=1

say()  { printf '%s\n   %s\n' "$1" "$2"; }               # English line + Vietnamese line
fail() { ulset_log ERROR "$1"; ERR_LIST+=("$1"); echo "  [ERROR] $1" >&2; }
warn() { ulset_log WARN "$1"; echo "  [WARN]  $1"; }

step() {   # step "English" "Tiếng Việt"
    STEP=$((STEP + 1))
    local pct=$(( (STEP - 1) * 100 / STEP_TOTAL ))
    ulset_bar "$pct" "$1 | $2"
    ulset_log INFO "STEP $STEP/$STEP_TOTAL: $1"
    ulset_notify "run" "ULSET - ($STEP/$STEP_TOTAL)" "$1"$'\n'"$2" normal 4000 "$pct"
}

ask() {   # ask "English question" "Vietnamese" default(y|n)  -> 0 = yes
    local def=${3:-n} a="" hint="[y/N]"
    [[ $def == y ]] && hint="[Y/n]"
    if (( ASSUME_YES )) || [[ ! -t 0 ]]; then [[ $def == y ]]; return; fi
    read -rp "$1 / $2 $hint " a || a=""
    [[ -z $a ]] && a=$def
    [[ $a =~ ^[Yy]$ ]]
}

finish_report() {   # finish_report "What"  -> prints + notifies, returns 0/1
    local what=$1 n=${#ERR_LIST[@]}
    ulset_bar 100 "$what finished | Hoàn tất"
    if (( n == 0 )); then
        ulset_log INFO "$what: SUCCESS, 0 errors"
        ulset_notify "run" "ULSET - $what OK" "Completed successfully, 0 errors."$'\n'"Hoàn tất thành công, 0 lỗi." normal 8000 100
        say "SUCCESS: $what completed with 0 errors." "THÀNH CÔNG: $what hoàn tất, 0 lỗi."
        return 0
    fi
    ulset_log ERROR "$what: finished with $n error(s)"
    ulset_notify "run" "ULSET - $what: $n error(s)" "Finished with $n error(s). See log:"$'\n'"Có $n lỗi. Xem log: $ULSET_LOG" critical 15000 100
    say "FINISHED WITH $n ERROR(S):" "HOÀN TẤT NHƯNG CÓ $n LỖI:"
    local e; for e in "${ERR_LIST[@]}"; do echo "   - $e"; done
    echo "   Log: $ULSET_LOG"
    return 1
}

# ==============================================================================
# [ 4. DEPENDENCIES ]  Add what is MISSING only. Never remove, never upgrade.
# ==============================================================================
pkg_installed() {
    case $ULSET_PKG_MGR in
        pacman) pacman -Qq "$1" >/dev/null 2>&1 ;;
        apt)    dpkg-query -W -f='${Status}' "$1" 2>/dev/null | grep -q 'install ok installed' ;;
        dnf|zypper) rpm -q "$1" >/dev/null 2>&1 ;;
        *) return 1 ;;
    esac
}

run_priv() {
    if ulset_have sudo && [[ -t 0 ]]; then sudo "$@"
    elif ulset_have pkexec; then pkexec "$@"
    elif ulset_have sudo; then sudo "$@"
    else echo "No sudo/pkexec available" >&2; return 1; fi
}

MISSING=()
collect_missing() {
    MISSING=()
    { ulset_have wine || ulset_have wine64; } || MISSING+=(wine)
    ulset_have winetricks || MISSING+=(winetricks)
    ulset_have cabextract || MISSING+=(cabextract)
    { ulset_have wrestool && ulset_have icotool; } || MISSING+=(icoutils)
    if [[ $ULSET_PKG_MGR == pacman ]]; then
        [[ -d /usr/share/wine/mono  ]] || pkg_installed wine-mono  || MISSING+=(wine-mono)
        [[ -d /usr/share/wine/gecko ]] || pkg_installed wine-gecko || MISSING+=(wine-gecko)
    fi
}

install_packages() {   # install_packages pkg...  (add-only)
    case $ULSET_PKG_MGR in
        pacman) run_priv pacman -S --needed --noconfirm "$@" ;;
        apt)    run_priv apt-get install -y --no-upgrade "$@" ;;
        dnf)    run_priv dnf install -y --setopt=install_weak_deps=False "$@" ;;
        zypper) run_priv zypper --non-interactive install --no-recommends "$@" ;;
        *)      return 1 ;;
    esac
}

ensure_wine_stack() {
    ulset_detect_env
    collect_missing
    if (( ${#MISSING[@]} == 0 )); then
        say "Wine and required tools already present - nothing installed, nothing upgraded." \
            "Wine và công cụ cần thiết đã có - không cài thêm, không nâng cấp."
        ulset_log INFO "DEPS: nothing missing"
        return 0
    fi
    say "Missing components (will be ADDED only): ${MISSING[*]}" "Thành phần còn thiếu (chỉ BỔ SUNG): ${MISSING[*]}"
    ulset_log INFO "DEPS: missing = ${MISSING[*]}"
    if (( ULSET_IMMUTABLE )); then
        warn "Immutable system (SteamOS/ostree): not touching system packages. Add them via Flatpak/your distro tools. / Hệ thống chỉ-đọc: không cài gói hệ thống."
        return 0
    fi
    if [[ $ULSET_PKG_MGR == none ]]; then
        fail "No supported package manager found; please install manually: ${MISSING[*]}"
        return 1
    fi
    ulset_notify "deps" "ULSET - Installing missing packages" "This may take a few minutes - the script is NOT frozen."$'\n'"Có thể mất vài phút - script không bị treo." normal 8000
    [[ $ULSET_PKG_MGR == apt ]] && run_priv apt-get update -qq
    if ! install_packages "${MISSING[@]}"; then
        warn "Batch install failed; retrying one by one / Cài hàng loạt lỗi, thử từng gói."
        local p
        for p in "${MISSING[@]}"; do
            install_packages "$p" || fail "Could not install package: $p"
        done
    fi
    collect_missing
    (( ${#MISSING[@]} == 0 )) && ulset_log INFO "DEPS: all components now present"
    return 0
}

