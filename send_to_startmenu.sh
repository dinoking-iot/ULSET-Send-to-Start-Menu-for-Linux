# --- logging (timestamped) ----------------------------------------------------
ulset_log() {   # ulset_log LEVEL message...
    local lvl=$1; shift
    [[ $lvl == ERROR ]] && ULSET_ERRORS=$((ULSET_ERRORS + 1))
    [[ -d $ULSET_LOG_DIR ]] || mkdir -p "$ULSET_LOG_DIR" 2>/dev/null
    printf '[%(%Y-%m-%d %H:%M:%S)T] [%s] %s\n' -1 "$lvl" "$*" 2>/dev/null >> "$ULSET_LOG"
    return 0
}

ulset_rotate_log() {   # keep the log under ~10 MB (one previous copy kept)
    local size
    size=$(stat -c %s "$ULSET_LOG" 2>/dev/null || echo 0)
    if (( size > 10485760 )); then
        mv -f "$ULSET_LOG" "$ULSET_LOG.1" 2>/dev/null && ulset_log INFO "Log rotated; previous copy: menushortcut_system.log.1"
    fi
    return 0
}

# Reads stdin, appends to the log with a rate limit (default 20 lines/second).
ulset_pipe_log() {   # ulset_pipe_log <TAG> [max-per-second]
    local tag=$1 max=${2:-20} line now sec=0 cnt=0 dropped=0
    while IFS= read -r line; do
        printf -v now '%(%s)T' -1
        if [[ $now != "$sec" ]]; then
            (( dropped > 0 )) && ulset_log INFO "[$tag] ... $dropped more line(s) suppressed (rate limit)"
            sec=$now; cnt=0; dropped=0
        fi
        if (( ++cnt <= max )); then ulset_log LOG "[$tag] $line"; else dropped=$((dropped + 1)); fi
    done
    (( dropped > 0 )) && ulset_log INFO "[$tag] ... $dropped more line(s) suppressed (rate limit)"
    return 0
}

# --- anti-spam notifications --------------------------------------------------
# One notification slot per <tag>: a new message REPLACES the previous one
# (same id) instead of stacking, and an identical message that is still on
# screen is skipped. Optional progress bar via the "value" hint.
ulset_notify() {   # ulset_notify <tag> <title> <message> [urgency] [timeout_ms] [progress 0-100]
    local tag=$1 title=$2 msg=$3 urgency=${4:-normal} timeout=${5:-6000} progress=${6:--1}
    local state="$ULSET_RUN/notify-$tag" now sig id="" last_id="" last_ts=0 last_sig=""
    printf -v now '%(%s)T' -1
    sig="$title|${msg//$'\n'/ }"   # single line: the state file is read line by line
    if [[ -r $state ]]; then IFS='|' read -r last_id last_ts last_sig < "$state"; fi
    [[ $last_ts =~ ^[0-9]+$ ]] || last_ts=0
    if [[ $sig == "$last_sig" ]] && (( now - last_ts < timeout / 1000 + 2 )); then return 0; fi
    if ulset_have notify-send; then
        local args=(-a "$ULSET_APP" -u "$urgency" -t "$timeout" -h "string:x-canonical-private-synchronous:ulset-$tag")
        (( progress >= 0 )) && args+=(-h "int:value:$progress")
        [[ $last_id =~ ^[0-9]+$ ]] && (( last_id > 0 )) && args+=(-r "$last_id")
        id=$(notify-send -p "${args[@]}" "$title" "$msg" 2>/dev/null) || id=""
        if [[ -z $id ]]; then
            notify-send -a "$ULSET_APP" -u "$urgency" -t "$timeout" "$title" "$msg" >/dev/null 2>&1
        fi
    elif ulset_have kdialog; then
        kdialog --title "$title" --passivepopup "$msg" "$(( timeout / 1000 ))" >/dev/null 2>&1 &
    fi
    [[ -d $ULSET_RUN ]] || mkdir -p "$ULSET_RUN" 2>/dev/null
    printf '%s|%s|%s\n' "${id:-0}" "$now" "$sig" 2>/dev/null > "$state"
    return 0
}

# --- terminal progress line ---------------------------------------------------
ulset_bar() {   # ulset_bar <percent> <label>
    [[ -t 1 ]] || return 0
    local pct=$1 label=$2 w=30 f i bar=""
    f=$(( pct * w / 100 ))
    for (( i = 0; i < w; i++ )); do if (( i < f )); then bar+="#"; else bar+="-"; fi; done
    printf '[%s] %3d%% %s\n' "$bar" "$pct" "$label"
}

# --- system detection ---------------------------------------------------------
ulset_detect_env() {
    local id="" like="" pretty=""
    if [[ -r /etc/os-release ]]; then
        id=$(. /etc/os-release; printf '%s' "${ID:-}")
        like=$(. /etc/os-release; printf '%s' "${ID_LIKE:-}")
        pretty=$(. /etc/os-release; printf '%s' "${PRETTY_NAME:-}")
    fi
    ULSET_OS_ID=${id,,}
    ULSET_OS_PRETTY=${pretty:-unknown}
    case " ${id,,} ${like,,} " in
        *" arch "*|*" biglinux "*|*" manjaro "*|*" endeavouros "*|*" steamos "*) ULSET_OS_FAMILY=arch ;;
        *" debian "*|*" ubuntu "*|*" deepin "*|*" zorin "*|*" linuxmint "*)      ULSET_OS_FAMILY=debian ;;
        *" fedora "*|*" rhel "*|*" nobara "*)                                    ULSET_OS_FAMILY=fedora ;;
        *suse*)                                                                   ULSET_OS_FAMILY=suse ;;
        *)                                                                        ULSET_OS_FAMILY=unknown ;;
    esac
    ULSET_PKG_MGR=none
    for _pm in pacman apt-get dnf zypper; do
        if ulset_have "$_pm"; then ULSET_PKG_MGR=${_pm/apt-get/apt}; break; fi
    done
    ULSET_IMMUTABLE=0
    if [[ -e /run/ostree-booted || $ULSET_OS_ID == steamos ]]; then ULSET_IMMUTABLE=1; fi
    ULSET_SESSION=${XDG_SESSION_TYPE:-}
    if [[ -z $ULSET_SESSION ]]; then
        if [[ -n ${WAYLAND_DISPLAY:-} ]]; then ULSET_SESSION=wayland
        elif [[ -n ${DISPLAY:-} ]]; then ULSET_SESSION=x11
        else ULSET_SESSION=unknown; fi
    fi
    ULSET_DE=${XDG_CURRENT_DESKTOP:-${DESKTOP_SESSION:-unknown}}
}

ulset_env_snapshot() {
    ulset_detect_env
    ulset_log INFO "ENV: os=$ULSET_OS_PRETTY | kernel=$(uname -r) | de=$ULSET_DE | session=$ULSET_SESSION | user=$(id -un) | pkg=$ULSET_PKG_MGR | immutable=$ULSET_IMMUTABLE"
    ulset_log INFO "ENV: wine=$(wine --version 2>/dev/null || echo 'not installed') | bash=${BASH_VERSION:-?}"
    local gpu
    gpu=$(lspci 2>/dev/null | grep -Ei 'vga|3d controller' | head -2 | sed 's/^[^ ]* //' | paste -sd';' -)
    [[ -n $gpu ]] && ulset_log INFO "ENV: gpu=$gpu"
    return 0
}

