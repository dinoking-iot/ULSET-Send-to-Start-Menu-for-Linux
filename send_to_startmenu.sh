main_menu() {
    local choice st
    ulset_env_snapshot
    "$ULSET_DAEMON" start >/dev/null 2>&1   # logger runs from now until reboot (only if installed)
    ulset_log INFO "MENU opened (v$ULSET_VERSION)"
    while true; do
        clear
        [[ -x $ULSET_HELPER ]] && st="INSTALLED / ĐÃ CÀI" || st="NOT INSTALLED / CHƯA CÀI"
        echo "=============================================================="
        echo "  ULSET - SEND TO START MENU            v$ULSET_VERSION"
        echo "  Gửi file / thư mục / .exe vào Start Menu bằng chuột phải"
        echo "=============================================================="
        echo "  OS: $ULSET_OS_PRETTY"
        echo "  Desktop: $ULSET_DE | Session: $ULSET_SESSION | User: $(id -un)"
        echo "  Status: $st | Shortcuts: $(count_shortcuts)"
        echo "  Log: $ULSET_LOG"
        echo "--------------------------------------------------------------"
        echo "  1. Install / Update             (Cài đặt / Cập nhật)"
        echo "  2. Uninstall                    (Gỡ cài đặt - Wine được giữ lại)"
        echo "  3. Remove all ULSET shortcuts   (Xóa mọi shortcut do ULSET tạo)"
        echo "  4. Check Wine components        (Chỉ bổ sung nếu thiếu, không nâng cấp)"
        echo "  5. Export diagnostic report     (Xuất báo cáo chẩn đoán)"
        echo "  6. Run self-test                (Kiểm tra tự động toàn bộ)"
        echo "  0. Exit                         (Thoát)"
        echo "=============================================================="
        read -rp "Select / Chọn (0-6): " choice || exit 0
        case "$choice" in
            1) install_all ;;
            2) uninstall_all ;;
            3) purge_action ;;
            4) wine_check_action ;;
            5) diag_report ;;
            6) selftest_action ;;
            0) echo "Bye / Tạm biệt."; exit 0 ;;
            *) echo "Invalid choice / Lựa chọn không hợp lệ." ;;
        esac
        read -rp "Press Enter to continue / Nhấn Enter để tiếp tục..." _ || exit 0
    done
}

case "$ACTION" in
    install)    install_all; exit $? ;;
    uninstall)  uninstall_all; exit $? ;;
    purge)      purge_action; exit $? ;;
    wine-check) wine_check_action; exit $? ;;
    diag)       diag_report; exit 0 ;;
    selftest)   selftest_action; exit $? ;;
    status)     show_status; exit 0 ;;
    help)       usage; exit 0 ;;
    "")         main_menu ;;
esac
