diag_report() {
    prepare_env
    local out="$ULSET_LOG_DIR/ULSET_diagnostic_$(date +%Y%m%d_%H%M%S).txt"
    ulset_env_snapshot
    {
        echo "ULSET diagnostic report - $(date -Is) - version $ULSET_VERSION"
        echo "(contains your user name and paths - review before sharing / có tên người dùng, hãy kiểm tra trước khi gửi)"
        echo; echo "== System =="
        echo "OS: $ULSET_OS_PRETTY | kernel: $(uname -r) | desktop: $ULSET_DE | session: $ULSET_SESSION | pkg: $ULSET_PKG_MGR"
        echo "wine: $(wine --version 2>/dev/null || echo missing) | winetricks: $(command -v winetricks || echo missing) | wrestool: $(command -v wrestool || echo missing)"
        echo; echo "== ULSET files =="
        local f
        for f in "$ULSET_HELPER" "$ULSET_LAUNCHER" "$ULSET_DAEMON" "$LIB_FILE" "${FM_FILES[@]}" "$FM_THUNAR"; do
            [[ -e $f ]] && echo "present: $f" || echo "absent : $f"
        done
        echo "shortcuts created: $(count_shortcuts)"
        echo "daemon: $("$ULSET_DAEMON" status 2>&1)"
        echo; echo "== Last 200 log lines =="
        tail -n 200 "$ULSET_LOG" 2>/dev/null
    } > "$out"
    ulset_log INFO "DIAG: report written to $out"
    say "Diagnostic report: $out" "Báo cáo chẩn đoán: $out"
    ulset_notify "diag" "ULSET - Diagnostic report" "$out" normal 8000
}

show_status() {
    ulset_detect_env
    local i
    [[ -x $ULSET_HELPER ]] && i="INSTALLED" || i="not installed"
    echo "ULSET $ULSET_VERSION: $i | shortcuts: $(count_shortcuts) | logger: $("$ULSET_DAEMON" status 2>&1 | head -1)"
    echo "OS: $ULSET_OS_PRETTY | $ULSET_DE | $ULSET_SESSION | Log: $ULSET_LOG"
}

daemon_diag() {   # why did the logger not start? -> into the log
    local t out
    [[ -s $ULSET_RUN/daemon.err ]] && ulset_log WARN "DAEMON stderr: $(head -c 400 "$ULSET_RUN/daemon.err" | tr '\n' ' ')"
    for t in flock setsid nice ionice; do ulset_have "$t" || ulset_log WARN "DAEMON: missing tool: $t"; done
    out=$(setsid timeout 3 bash -x "$ULSET_DAEMON" run 2>&1 </dev/null | tail -n 12 | tr '\n' '|')
    ulset_log WARN "DAEMON trace: $out"
}

st_ok()   { SELF_PASS=$((SELF_PASS + 1)); printf '    [PASS] %s\n' "$1"; ulset_log INFO "SELFTEST PASS: $1"; }
st_warn() { printf '    [WARN] %s\n' "$1"; ulset_log WARN "SELFTEST WARN: $1"; }
st_bad()  { ERR_LIST+=("Self-test: $1"); printf '    [FAIL] %s\n' "$1"; ulset_log ERROR "SELFTEST FAIL: $1"; }

# Verifies the whole chain: programs, tools, right-click entry, a real shortcut
# round-trip (create -> command resolves -> removed), logger, journal access.
selftest() {   # selftest [keep]   (keep = do not reset the error list)
    [[ ${1:-} == keep ]] || ERR_LIST=()
    SELF_PASS=0
    local f line tmpd src desk out i fm=0
    echo "  Self-test / Kiểm tra tự động:"
    ulset_detect_env
    for f in "$ULSET_HELPER" "$ULSET_LAUNCHER" "$ULSET_DAEMON"; do
        if [[ -x $f ]] && bash -n "$f" 2>/dev/null; then st_ok "Program OK: ${f##*/}"; else st_bad "Program missing or broken: $f"; fi
    done
    if [[ -r $LIB_FILE ]]; then st_ok "Library OK"; else st_bad "Library missing: $LIB_FILE"; fi
    for f in flock setsid nice; do
        if ulset_have "$f"; then st_ok "Tool present: $f"; else st_bad "Missing tool: $f (package util-linux / coreutils)"; fi
    done
    if ulset_have xdg-open || ulset_have kde-open || ulset_have gio; then st_ok "File opener present"; else st_bad "No file opener (xdg-open / kde-open / gio)"; fi
    ulset_have notify-send || st_warn "notify-send missing: pop-up notifications will be limited (package libnotify)"
    ulset_have wine || ulset_have wine64 || st_warn "Wine not installed: .exe shortcuts will not run (menu option 4)"
    for f in "${FM_FILES[@]}"; do [[ -e $f ]] && fm=1; done
    grep -q 'ulset-send-to-startmenu' "$FM_THUNAR" 2>/dev/null && fm=1
    if (( fm )); then st_ok "Right-click action installed"; else st_bad "No right-click action found"; fi

    if [[ -x $ULSET_HELPER ]]; then
        tmpd=$(mktemp -d); src="$tmpd/ULSET selftest.txt"; printf 'ULSET self-test\n' > "$src"
        "$ULSET_HELPER" "$src" >/dev/null 2>&1
        desk=""
        for (( i = 0; i < 24; i++ )); do
            desk=$(grep -lxF "X-ULSET-Source=$src" "$ULSET_APPS_DIR"/ulset-*.desktop 2>/dev/null | head -n1)
            [[ -n $desk ]] && break
            sleep 0.25
        done
        if [[ -n $desk ]]; then
            st_ok "Helper created a Start Menu shortcut"
            line=$(sed -n 's/^Exec=//p' "$desk" | head -n1)
            out=$(eval "set -- $line; ULSET_DRY_RUN=1 \"\$@\"" 2>&1)
            if [[ $out == *mode=open* ]]; then st_ok "Shortcut command resolves correctly"; else st_bad "Shortcut command did not run: ${out:-no output}"; fi
            rm -f "$desk"
        else
            st_bad "Helper did NOT create a shortcut. Run this to see the error:  $ULSET_HELPER \"$src\""
        fi
        printf 'not a program\n' > "$tmpd/fake.docx"; chmod +x "$tmpd/fake.docx"   # like NTFS/exFAT
        out=$(ULSET_DRY_RUN=1 "$ULSET_LAUNCHER" "$tmpd/fake.docx" 2>&1)
        if [[ $out == *mode=open* ]]; then st_ok "Documents marked executable (NTFS/exFAT) are opened, not executed"
        else st_bad "A document with the x bit would be executed instead of opened: ${out:-no output}"; fi
        rm -rf "$tmpd"
        ulset_refresh_menu
    fi

    for (( i = 0; i < 40; i++ )); do ulset_daemon_alive && break; sleep 0.25; done
    if ulset_daemon_alive; then st_ok "Background logger running"; else st_warn "Background logger not running (starts on first use)"; fi
    if ulset_have journalctl && ! timeout 5 journalctl --user -n1 -q >/dev/null 2>&1; then
        st_warn "System journal not readable: add your user to the 'systemd-journal' group for full game/kernel logging"
    fi
    echo "  Self-test result: $SELF_PASS passed, $(( ${#ERR_LIST[@]} )) failed."
    return 0
}

selftest_action() {
    prepare_env
    ERR_LIST=(); STEP=0; STEP_TOTAL=1
    step "Running self-test" "Chạy kiểm tra tự động"
    selftest keep
    finish_report "Self-test"
}

usage() {
    cat <<EOF
ULSET $ULSET_VERSION - Send to Start Menu / Gửi vào Start Menu

Usage: $(basename "$0") [--yes] [--install | --uninstall | --purge | --wine-check | --selftest | --diag | --status | --help]
  (no option)   interactive menu / menu tương tác
  --install     install or update (safe to repeat) / cài hoặc cập nhật
  --uninstall   remove everything ULSET added (Wine stays) / gỡ toàn bộ (giữ Wine)
  --purge       remove all shortcuts created by ULSET / xóa mọi shortcut đã tạo
  --wine-check  add missing Wine components only, never upgrade / chỉ bổ sung thành phần thiếu
  --selftest    check that everything works end to end / kiểm tra tự động toàn bộ
  --diag        write a diagnostic report to Documents / xuất báo cáo chẩn đoán
  --yes         assume the default answer to every question / tự trả lời mặc định
EOF
}

