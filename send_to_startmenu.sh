#!/usr/bin/env bash
# ==============================================================================
# ULSET - "Send to Start Menu"   (Universal Linux Shortcut Environment Tool)
# VERSION : 2026.10.18_v16
# TARGET  : BigLinux (priority), Arch/Manjaro, Ubuntu/Debian/Mint/Zorin/Deepin,
#           Fedora, openSUSE | KDE Plasma, GNOME, XFCE, Cinnamon, MATE, LXQt...
#           Wayland and X11.
#
# WHAT IT DOES / TÁC DỤNG
#   Adds a right-click action "Send to Start Menu" to your file manager. It
#   creates a real Start Menu entry for any file, folder, script or Windows
#   program (.exe/.msi/.bat/.lnk, run through Wine).
#
# SAFETY RULES / QUY TẮC AN TOÀN
#   - Never removes or upgrades BigLinux, Wine or any Wine component that is
#     already installed. Only ADDS what is missing (pacman --needed, apt
#     --no-upgrade ...). Never runs a system update.
#   - No autostart, no systemd unit, no /etc changes, nothing at login/shutdown.
#   - Everything lives in your home folder; Uninstall removes it all again.
#   - Runs as the CURRENT user (never root).
#
# CLI (for technicians) / DÒNG LỆNH
#   send_to_startmenu.sh [--yes] --install | --uninstall | --purge |
#                        --wine-check | --diag | --status | --help
# ==============================================================================
