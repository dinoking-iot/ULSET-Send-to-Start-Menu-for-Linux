count_shortcuts() { local n=0 f; for f in "$ULSET_APPS_DIR"/ulset-*.desktop; do [[ -e $f ]] && n=$((n+1)); done; echo "$n"; }

kill_legacy() {   # v14 daemon (exec -a ulset_shortcut_daemon)
    pkill -u "$(id -u)" -f '^ulset_shortcut_daemon' 2>/dev/null
    return 0
}

install_all() {
    prepare_env
    ERR_LIST=(); STEP=0; STEP_TOTAL=7
    ulset_log INFO "===== INSTALL start ($ULSET_VERSION) ====="

    step "Checking your system" "Đang kiểm tra hệ thống"
    ulset_env_snapshot
    echo "  OS: $ULSET_OS_PRETTY | Desktop: $ULSET_DE | Session: $ULSET_SESSION | Packages: $ULSET_PKG_MGR"

    step "Checking Wine and tools (adds only what is missing, never upgrades)" "Kiểm tra Wine và công cụ (chỉ bổ sung nếu thiếu, không nâng cấp)"
    ensure_wine_stack

    step "Installing helper programs" "Đang cài các chương trình hỗ trợ"
    "$ULSET_DAEMON" stop >/dev/null 2>&1
    kill_legacy
    mkdir -p "$ULSET_BIN_DIR" "$ULSET_ICON_DIR"
    write_helper   || fail "Could not write $ULSET_HELPER"
    write_launcher || fail "Could not write $ULSET_LAUNCHER"
    write_daemon   || fail "Could not write $ULSET_DAEMON"
    "$ULSET_HELPER" --regenerate    # upgrade shortcuts made by older versions

    step "Adding right-click action to your file manager(s)" "Thêm mục chuột phải vào trình quản lý tệp"
    install_fm_integrations || fail "No right-click integration could be installed"

    step "Starting the background logger and writing the patch history" "Bật tiến trình ghi log nền và ghi nhật ký bản vá"
    write_patch_history
    "$ULSET_DAEMON" start >/dev/null 2>&1
    local i
    for (( i = 0; i < 40; i++ )); do ulset_daemon_alive && break; sleep 0.25; done
    if ulset_daemon_alive; then
        echo "  Logger running until reboot (no autostart)."
    else
        warn "Background logger not running yet; it will start on first use. Details are in the log. / Logger chưa chạy, sẽ tự bật khi dùng."
        daemon_diag
    fi

    step "Refreshing the menu cache" "Làm mới bộ nhớ đệm menu"
    ulset_refresh_menu full

    step "Running a quick self-test" "Chạy kiểm tra tự động"
    selftest keep

    ulset_log INFO "===== INSTALL end: ${#ERR_LIST[@]} error(s) ====="
    finish_report "Install"
    local rc=$?
    echo "  If the right-click entry is missing, close and reopen your file manager."
    echo "  Nếu chưa thấy mục chuột phải, hãy đóng và mở lại trình quản lý tệp."
    return $rc
}

purge_shortcuts() {
    local n=0 f m
    for f in "$ULSET_APPS_DIR"/ulset-*.desktop; do
        [[ -e $f ]] || continue
        rm -f "$f"; n=$((n+1))
    done
    rm -rf "$ULSET_ICON_DIR"
    for m in "$ULSET_CONFIG_HOME"/menus/*kmenuedit*.menu; do   # stale Menu Editor rules (backup kept)
        [[ -f $m ]] || continue
        grep -q '<Filename>ulset-' "$m" || continue
        cp -f "$m" "$m.bak" && sed -i '/<Filename>ulset-[^<]*<\/Filename>/d' "$m"
    done
    ulset_refresh_menu full
    ulset_log INFO "PURGE: removed $n shortcut(s)"
    PURGED=$n
}

purge_action() {
    prepare_env
    ERR_LIST=(); STEP=0; STEP_TOTAL=1
    step "Removing shortcuts created by ULSET" "Xóa các shortcut do ULSET tạo"
    purge_shortcuts
    say "Removed $PURGED shortcut(s)." "Đã xóa $PURGED shortcut."
    finish_report "Purge"
}

uninstall_all() {
    ERR_LIST=(); STEP=0; STEP_TOTAL=4
    ulset_log INFO "===== UNINSTALL start ====="
    local n keep=0
    n=$(count_shortcuts)

    step "Stopping the background logger" "Dừng tiến trình ghi log nền"
    "$ULSET_DAEMON" stop >/dev/null 2>&1
    kill_legacy

    step "Removing right-click actions" "Gỡ mục chuột phải"
    remove_fm_integrations

    step "Shortcuts created by ULSET: $n" "Các shortcut do ULSET tạo: $n"
    if (( n > 0 )); then
        if ask "Remove those $n shortcut(s) too? (If kept, the launcher stays installed so they keep working)" \
               "Xóa luôn $n shortcut? (Nếu giữ lại, launcher vẫn được giữ để shortcut còn chạy)" y; then
            purge_shortcuts
        else
            keep=1
        fi
    fi

    step "Removing helper programs and temporary files" "Gỡ chương trình hỗ trợ và tệp tạm"
    rm -f "$ULSET_HELPER"
    if (( keep )); then
        say "Kept ulset-launch, ulset-daemon and the library (needed by your shortcuts)." \
            "Giữ lại ulset-launch, ulset-daemon và thư viện (shortcut đang cần)."
    else
        rm -f "$ULSET_LAUNCHER" "$ULSET_DAEMON"
        rm -rf "$ULSET_ICON_DIR"
        rm -f "$LIB_FILE"; rmdir "$LIB_DIR" "$ULSET_HOME_DIR" 2>/dev/null
    fi
    say "Wine, BigLinux and every system package were left untouched." "Wine, BigLinux và các gói hệ thống được giữ nguyên."
    ulset_log INFO "===== UNINSTALL end ====="
    finish_report "Uninstall"
    local rc=$?
    rm -rf "$ULSET_RUN"
    if ask "Also delete the log folder ($ULSET_LOG_DIR)?" "Xóa luôn thư mục log?" n; then rm -rf "$ULSET_LOG_DIR"; fi
    return $rc
}

