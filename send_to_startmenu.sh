# Extract the largest icon of a .exe to PNG. 0 = success.
extract_icon() {   # extract_icon <exe> <out.png>
    { ulset_have wrestool && ulset_have icotool; } || return 1
    local tmp ico png
    tmp=$(mktemp -d) || return 1
    wrestool -x -t 14 -o "$tmp" "$1" >/dev/null 2>&1
    ico=$(ls -S "$tmp"/*.ico 2>/dev/null | head -n1)
    if [[ -n $ico ]]; then
        icotool -x -o "$tmp" "$ico" >/dev/null 2>&1
        png=$(ls -S "$tmp"/*.png 2>/dev/null | head -n1)
        [[ -n $png ]] && cp -f "$png" "$2"
    fi
    rm -rf "$tmp"
    [[ -s $2 ]]
}

# KDE Menu Editor "Delete" writes <Exclude><Filename>id</Filename></Exclude> into
# ~/.config/menus/*kmenuedit*.menu: that file name never shows again. Detect it.
is_excluded() {   # is_excluded <desktop-file-id>
    local m
    for m in "$ULSET_CONFIG_HOME"/menus/*kmenuedit*.menu; do
        [[ -f $m ]] || continue
        awk -v id="$1" '
            /<Exclude>/ {ex=1}
            ex && index($0, "<Filename>" id "</Filename>") {found=1}
            /<\/Exclude>/ {ex=0}
            END {exit !found}' "$m" && return 0
    done
    return 1
}

find_existing() {   # still-valid shortcut for this source? (hidden/excluded ones are cleaned)
    local f
    for f in "$ULSET_APPS_DIR"/ulset-*.desktop; do
        [[ -e $f ]] || continue
        grep -qxF "X-ULSET-Source=$1" "$f" || continue
        if grep -qiE '^(Hidden|NoDisplay)=true' "$f" || is_excluded "${f##*/}"; then
            rm -f "$f" "$ULSET_ICON_DIR/$(basename "$f" .desktop).png"
            ulset_log INFO "CLEAN: removed hidden/excluded shortcut: $f"
            continue
        fi
        printf '%s' "$f"
        return 0
    done
    return 1
}

create_one() {
    local src base name ext_lc slug mime icon exec_line path_dir desktop q want_icon=0 is_win=0

    src=$(readlink -f -- "$1") || { ulset_log ERROR "readlink failed: $1"; return 1; }
    [[ -e $src ]] || { ulset_log ERROR "Not found: $1"; return 1; }

    base=${src##*/}
    ext_lc=""
    [[ $base == *.* ]] && ext_lc=${base##*.} && ext_lc=${ext_lc,,}
    if [[ -f $src && $base == *.* ]]; then name=${base%.*}; else name=$base; fi
    [[ -n $name ]] || name=$base

    if [[ -d $src ]]; then path_dir=$src; else path_dir=${src%/*}; fi
    [[ -n $path_dir ]] || path_dir=/

    if ! desktop=$(find_existing "$src"); then
        slug=$(printf '%s' "$name" | tr '[:upper:]' '[:lower:]' | tr -c 'a-z0-9\n' '-' | sed 's/--*/-/g; s/^-//; s/-$//')
        [[ -n $slug ]] || slug=app
        desktop="$ULSET_APPS_DIR/ulset-$slug-$(date +%s)$RANDOM.desktop"   # unique name every time
    fi

    q=$(ulset_exec_quote "$src")
    mime=$(xdg-mime query filetype "$src" 2>/dev/null)
    [[ -n $mime ]] || mime=$(file -b --mime-type "$src" 2>/dev/null)
    icon=${mime//\//-}
    [[ -n $icon ]] || icon=text-x-generic
    [[ -d $src ]] && icon=folder

    if [[ -f $src ]]; then case $ext_lc in exe|msi|bat|lnk) is_win=1 ;; esac; fi

    # Every shortcut (exe, txt, doc, xls, pdf, folder, script...) goes through
    # ulset-launch: it picks Wine / direct run / default app and LOGS any failure.
    if [[ ! -x $ULSET_LAUNCHER ]]; then ulset_log ERROR "Launcher missing: $ULSET_LAUNCHER"; return 1; fi
    exec_line="$(ulset_exec_quote "$ULSET_LAUNCHER") $q"
    if (( is_win )); then
        icon=wine
        [[ $ext_lc == exe ]] && want_icon=1
    fi

    {
        printf '[Desktop Entry]\n'
        printf 'Version=1.0\n'
        printf 'Type=Application\n'
        printf 'Name=%s\n' "$name"
        printf 'Exec=%s\n' "$exec_line"
        printf 'Path=%s\n' "$path_dir"
        printf 'Icon=%s\n' "$icon"
        printf 'Terminal=false\n'
        printf 'StartupNotify=false\n'
        printf 'Categories=Utility;\n'
        printf 'X-ULSET-Source=%s\n' "$src"
    } > "$desktop.tmp" && mv -f "$desktop.tmp" "$desktop" || { ulset_log ERROR "Cannot write $desktop"; return 1; }

    chmod +x "$desktop"
    ulset_log INFO "SHORTCUT: $src -> $desktop"
    (( want_icon )) && ulset_detach "$SELF" --finish-icon "$src" "$desktop"
    return 0
}

# Background mode: extract the .exe icon after the shortcut is already visible.
if [[ ${1:-} == --finish-icon ]]; then
    iconfile="$ULSET_ICON_DIR/$(basename "$3" .desktop).png"
    if [[ -f $3 ]] && extract_icon "$2" "$iconfile"; then
        ICON="$iconfile" awk '/^Icon=/{print "Icon=" ENVIRON["ICON"]; next} {print}' "$3" > "$3.tmp" \
            && mv -f "$3.tmp" "$3" && chmod +x "$3"
        ulset_log INFO "ICON: $iconfile"
        ulset_refresh_menu
    else
        ulset_log INFO "ICON: could not extract icon from $2 (keeping generic Wine icon)"
    fi
    exit 0
fi

# Rewrite every existing ULSET shortcut with the current format (migration).
if [[ ${1:-} == --regenerate ]]; then
    n=0
    for f in "$ULSET_APPS_DIR"/ulset-*.desktop; do
        [[ -e $f ]] || continue
        src=$(sed -n 's/^X-ULSET-Source=//p' "$f" | head -n1)
        [[ -n $src && -e $src ]] || continue
        create_one "$src" && n=$((n + 1))
    done
    ulset_refresh_menu
    ulset_log INFO "REGENERATE: updated $n existing shortcut(s)"
    exit 0
fi

[[ $# -gt 0 ]] || { echo "Usage: ulset-create-shortcut <file-or-folder>..." >&2; exit 2; }

t0=$(date +%s%N)
ulset_log INFO "CALL: $# item(s): $*"
ok=0; fail=0
for f in "$@"; do
    if create_one "$f"; then ok=$((ok + 1)); else fail=$((fail + 1)); fi
done
ulset_refresh_menu
ulset_log INFO "DONE: ok=$ok fail=$fail in $(( ($(date +%s%N) - t0) / 1000000 )) ms"

if (( fail == 0 )); then
    ulset_notify "shortcut" "ULSET - Start Menu" "Created $ok shortcut(s)."$'\n'"Đã tạo $ok shortcut." normal 4000
else
    ulset_notify "shortcut" "ULSET - Start Menu: $fail error(s)" "Created $ok, failed $fail. Log: $ULSET_LOG"$'\n'"Tạo $ok, lỗi $fail." critical 10000
fi
( ulset_ensure_daemon >/dev/null 2>&1 & )   # logger starts AFTER the real work, never blocks it
HELPER_EOF
}

# ---- 5b. ulset-launch : runs Windows programs via Wine and logs their errors --
write_launcher() { write_exec "$ULSET_LAUNCHER" <<'LAUNCH_EOF'
#!/usr/bin/env bash
# ulset-launch - opens whatever a ULSET Start Menu entry points to, and logs failures.
#   .exe/.msi/.bat/.lnk          -> the Wine that is already installed (never modified)
#   executables and .sh scripts  -> run directly
#   everything else (txt, doc, xls, pdf, folders...) -> your default application,
#                                   trying xdg-open, kde-open, gio, exo-open in turn
set -u
ULSET_LIB="${XDG_DATA_HOME:-$HOME/.local/share}/ulset/lib/ulset-common.sh"
[[ -r $ULSET_LIB ]] || { echo "ULSET library missing: $ULSET_LIB" >&2; exit 1; }
. "$ULSET_LIB"

target=${1:-}
[[ -n $target ]] || { echo "Usage: ulset-launch <file-or-folder>" >&2; exit 2; }
target=$(readlink -f -- "$target")
name=${target##*/}
dir=${target%/*}; [[ -d $target ]] && dir=$target

if [[ ! -e $target ]]; then
    ulset_log ERROR "LAUNCH: file not found: $target"
    ulset_notify "launch" "ULSET - File not found" "$target"$'\n'"Không tìm thấy tệp (đã bị xóa hoặc di chuyển?)." critical 10000
    exit 1
fi

ext=""; [[ $name == *.* ]] && ext=${name##*.} && ext=${ext,,}
mode=open
if [[ -f $target ]]; then
    case $ext in
        exe|msi|bat|lnk) mode=wine ;;
        sh)              mode=bash ;;
        *)
            # NTFS / exFAT / FAT partitions mark EVERY file as executable, so the x bit proves
            # nothing. Treat a file as a program only if it really is an ELF binary or a "#!" script.
            if [[ -x $target ]]; then
                hdr=$(head -c4 -- "$target" 2>/dev/null | od -An -tx1 | tr -d ' \n')
                case $hdr in 7f454c46*|2321*) mode=native ;; esac
            fi ;;
    esac
fi
[[ ${ULSET_DRY_RUN:-} == 1 ]] && { echo "mode=$mode"; exit 0; }   # used by the self-test
( ulset_ensure_daemon >/dev/null 2>&1 & )

# ---- default application -----------------------------------------------------
open_default() {
    local tmp o rc
    tmp=$(mktemp) || return 1
    for o in "xdg-open" "kde-open" "kde-open6" "gio open" "exo-open" "gnome-open"; do
        ulset_have "${o%% *}" || continue
        # shellcheck disable=SC2086
        $o "$target" >"$tmp" 2>&1
        rc=$?
        if (( rc == 0 )); then
            ulset_log INFO "OPEN: $name via ${o%% *}"
            rm -f "$tmp"; return 0
        fi
        ulset_log WARN "OPEN: ${o%% *} failed for $name (rc=$rc): $(head -c 300 "$tmp" | tr '\n' ' ')"
    done
    rm -f "$tmp"
    return 1
}

if [[ $mode == open ]]; then
    if open_default; then exit 0; fi
    ulset_log ERROR "OPEN: no opener could open $target (is an application installed for this file type?)"
    ulset_notify "launch" "ULSET - Cannot open $name" "No application opened this file. Log: $ULSET_LOG"$'\n'"Không mở được tệp - có thể chưa cài ứng dụng phù hợp." critical 12000
    exit 1
fi

# ---- programs (Wine / native / script) -----------------------------------------
if [[ $mode == wine ]]; then
    WINE_BIN=$(command -v wine || command -v wine64 || true)
    if [[ -z $WINE_BIN ]]; then
        ulset_log ERROR "LAUNCH: Wine is not installed, cannot run $name"
        ulset_notify "launch" "ULSET - Wine not found" "Run ULSET and choose 'Check Wine components'."$'\n'"Chưa có Wine - chạy ULSET, chọn mục 4." critical 12000
        exit 127
    fi
    # Report (never block) well-known anti-cheat files that Wine may not support.
    scan_anticheat() {
        local hits
        hits=$(timeout 3 find "$1" -maxdepth 2 \( -iname 'EasyAntiCheat*' -o -iname 'BEService*' -o -iname 'BattlEye*' \
            -o -iname 'vgc.exe' -o -iname 'FACEIT*' -o -iname 'xigncode*' -o -iname 'GameGuard*' -o -iname 'npgg*' \
            -o -iname 'pnkbstr*' -o -iname 'mhyprot*' \) -printf '%f\n' 2>/dev/null | sort -u | head -5 | paste -sd, -)
        [[ -n $hits ]] || return 0
        ulset_log WARN "ANTICHEAT: $hits found next to $name. Online play may be blocked under Wine unless the developer enabled Linux support (see areweanticheatyet.com)"
        ulset_notify "anticheat" "ULSET - Anti-cheat detected" "$hits"$'\n'"Online play may not work on Linux unless the game supports it (areweanticheatyet.com)."$'\n'"Có thể không chơi online được trên Linux." normal 12000
    }
    ( scan_anticheat "$dir" >/dev/null 2>&1 ) &
    export WINEDEBUG="${WINEDEBUG:-fixme-all,err+all}"
    if [[ $ext == exe ]]; then cmd=("$WINE_BIN" "$target"); else cmd=("$WINE_BIN" start /wait /unix "$target"); fi
    ver=$("$WINE_BIN" --version 2>/dev/null)
elif [[ $mode == bash ]]; then
    cmd=(bash "$target"); ver="bash"
else
    cmd=("$target"); ver="native"
fi

cd "$dir" 2>/dev/null || true
ulset_log INFO "START: $name | $mode | ${ver:-} | $target"
start=$SECONDS
"${cmd[@]}" 2>&1 | ulset_pipe_log "APP:$name"
rc=${PIPESTATUS[0]}
dur=$(( SECONDS - start ))

if (( rc != 0 && dur < 15 )); then
    ulset_log ERROR "EXIT: $name closed after ${dur}s with code $rc (probably failed to start)"
    ulset_notify "launch" "ULSET - $name closed unexpectedly" "Exit code $rc after ${dur}s. Log: $ULSET_LOG"$'\n'"Ứng dụng đóng bất thường." critical 12000
else
    ulset_log INFO "EXIT: $name code=$rc after ${dur}s"
fi
exit "$rc"
LAUNCH_EOF
}

# ---- 5c. ulset-daemon : background logger, lives until logout/reboot ----------
write_daemon() { write_exec "$ULSET_DAEMON" <<'DAEMON_EOF'
#!/usr/bin/env bash
# ulset-daemon - low-priority background logger.
#  * Started on demand (when ULSET / a shortcut / the launcher runs). NO autostart.
#  * Single instance (flock). Ends at logout/reboot or with: ulset-daemon stop
#  * Records Wine/Proton/game and crash messages from the user journal and kernel
#    log into ~/Documents/ULSET_Logs/menushortcut_system.log (timestamped).
set -u
ULSET_LIB="${XDG_DATA_HOME:-$HOME/.local/share}/ulset/lib/ulset-common.sh"
[[ -r $ULSET_LIB ]] || exit 1
. "$ULSET_LIB"
SELF=$(readlink -f "$0")

USER_PAT='wine|proton|dxvk|vkd3d|\.exe|ulset|segfault|coredump|core dumped|anticheat|anti-cheat|easyanticheat|battleye'
KERNEL_PAT='segfault|general protection|trap invalid|wine|proton|oom-killer|out of memory|ptrace|nvrm|amdgpu.*(fail|error|timeout|hang)|i915.*(error|hang)|gpu hang'

follow() {   # follow <tag> <pattern> <journalctl args...>
    local tag=$1 pat=$2 tries=0 t0 t1 err="$ULSET_RUN/jc-$1.err"
    shift 2
    while (( tries < 5 )); do
        printf -v t0 '%(%s)T' -1
        journalctl "$@" -f -n0 -o short-iso --no-pager 2>"$err" \
            | grep --line-buffered -Ei -- "$pat" | ulset_pipe_log "SYS:$tag"
        printf -v t1 '%(%s)T' -1
        if (( t1 - t0 < 5 )); then
            tries=$((tries + 1))
            [[ -s $err ]] && ulset_log WARN "journal($tag): $(head -c 200 "$err" | tr '\n' ' ')"
            sleep 30
        else
            tries=0
        fi
    done
    ulset_log WARN "journal follower '$tag' stopped (no permission? add your user to the 'systemd-journal' group to enable it)"
}

run_daemon() {
    exec 9>"$ULSET_RUN/daemon.lock"
    flock -n 9 || exit 0
    printf '%s\n' "$$" > "$ULSET_RUN/daemon.pid"
    trap 'trap - TERM INT EXIT; rm -f "$ULSET_RUN/daemon.pid"; kill 0 2>/dev/null; exit 0' TERM INT
    trap '' HUP
    ulset_log INFO "DAEMON: started (pid $$, $ULSET_VERSION). Runs until logout/reboot; no autostart."
    ulset_env_snapshot
    if ulset_have journalctl; then
        follow user   "$USER_PAT"   --user 9>&- &
        follow kernel "$KERNEL_PAT" -k     9>&- &
    else
        ulset_log WARN "DAEMON: journalctl not found - system event logging disabled (game logs still work)"
    fi
    while :; do
        sleep 60 & wait $!
        # Runtime dir wiped (logout/reboot) or replaced by a newer daemon -> exit.
        [[ $(cat "$ULSET_RUN/daemon.pid" 2>/dev/null) == "$$" ]] || exit 0
        ulset_rotate_log
    done
}

case ${1:-start} in
    start)
        ulset_daemon_alive && exit 0
        err="$ULSET_RUN/daemon.err"
        if ulset_have ionice; then set -- nice -n 10 ionice -c2 -n7 "$SELF" run; else set -- nice -n 10 "$SELF" run; fi
        setsid -f "$@" </dev/null >/dev/null 2>"$err" || { nohup setsid "$@" </dev/null >/dev/null 2>>"$err" & }
        ;;
    run)    run_daemon ;;
    stop)
        if ulset_daemon_alive; then
            kill "$(cat "$ULSET_RUN/daemon.pid")" 2>/dev/null
            sleep 0.3
            rm -f "$ULSET_RUN/daemon.pid"
            ulset_log INFO "DAEMON: stopped"
        fi
        ;;
    status) if ulset_daemon_alive; then echo "running (pid $(cat "$ULSET_RUN/daemon.pid"))"; else echo "not running"; exit 1; fi ;;
    *) echo "Usage: ulset-daemon start|stop|status" >&2; exit 2 ;;
esac
DAEMON_EOF
}

